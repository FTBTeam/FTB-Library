package dev.ftb.mods.ftblibrary.ui.layout;

/**
 * Alignment of a widget within the space available to it along one axis.
 */
public enum Align {
    /** Left edge (horizontal axis) or top edge (vertical axis). */
    START,
    /** Centered; any odd leftover pixel goes to the end side. */
    CENTER,
    /** Right edge (horizontal axis) or bottom edge (vertical axis). */
    END
}
